"""Recolourable SVG icons for the Qt UI.

Icons in ``GUI/icons/tintable`` (generated by ``tools/make_tintable_icons.py``)
paint with ``currentColor``. :func:`tinted_icon` wraps one in a ``QIcon``
whose engine renders the SVG on demand:

* at the exact size Qt requests, so icons stay sharp at every UI scale and
  device-pixel ratio;
* in a colour resolved from the application palette *at paint time*, so a
  theme or accent change recolours every icon without rebuilding widgets.

Colours are given as palette role names (``"Highlight"`` = accent,
``"PlaceholderText"`` = muted text, ``"Text"`` ...) or literal colours.
Checkable buttons can use different icons and colours for the on/off states,
e.g. the Scene Actors visibility toggle::

    tinted_icon("visible", on_color="Highlight",
                off_name="invisible", off_color="PlaceholderText")
"""
from __future__ import annotations

import os
import sys
from functools import lru_cache

if sys.platform == 'darwin':
    from PyQt5.QtCore import QByteArray, QRectF, QSize, Qt
    from PyQt5.QtGui import (
        QColor, QGuiApplication, QIcon, QIconEngine, QPainter, QPalette, QPixmap)
    from PyQt5.QtSvg import QSvgRenderer
else:
    from PyQt6.QtCore import QByteArray, QRectF, QSize, Qt
    from PyQt6.QtGui import (
        QColor, QGuiApplication, QIcon, QIconEngine, QPainter, QPalette, QPixmap)
    from PyQt6.QtSvg import QSvgRenderer

TINTABLE_DIR = os.path.join(os.path.dirname(__file__), "icons", "tintable")

_MODE = getattr(QIcon, "Mode", QIcon)
_STATE = getattr(QIcon, "State", QIcon)
_ROLE = getattr(QPalette, "ColorRole", QPalette)
_GROUP = getattr(QPalette, "ColorGroup", QPalette)


@lru_cache(maxsize=None)
def _svg_source(name: str) -> str:
    path = os.path.join(TINTABLE_DIR, f"{name}.svg")
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def available_icons() -> list[str]:
    """Names of the icons that can be tinted."""
    return sorted(f[:-4] for f in os.listdir(TINTABLE_DIR) if f.endswith(".svg"))


def resolve_color(color) -> QColor:
    """Resolve a palette role name, colour string or QColor."""
    if isinstance(color, QColor):
        return QColor(color)
    if isinstance(color, (tuple, list)):
        return QColor.fromRgbF(*color)
    role = getattr(_ROLE, str(color), None)
    if role is not None:
        return QGuiApplication.palette().color(role)
    resolved = QColor(str(color))
    if not resolved.isValid():
        raise ValueError(f"unknown icon colour {color!r}")
    return resolved


@lru_cache(maxsize=512)
def _renderer(name: str, rgba: str) -> QSvgRenderer:
    svg = _svg_source(name).replace("currentColor", rgba)
    return QSvgRenderer(QByteArray(svg.encode("utf-8")))


class TintedSvgIconEngine(QIconEngine):
    """QIconEngine drawing a tintable SVG in palette-resolved colours."""

    def __init__(self, name, color="Text", off_name=None, off_color=None,
                 disabled_color=None):
        super().__init__()
        for icon_name in filter(None, (name, off_name)):
            _svg_source(icon_name)  # fail early on a missing icon
        self.name = name
        self.color = color
        self.off_name = off_name
        self.off_color = off_color
        self.disabled_color = disabled_color

    def _pick(self, mode, state):
        off = state == _STATE.Off
        name = (self.off_name or self.name) if off else self.name
        color = (self.off_color or self.color) if off else self.color
        if mode == _MODE.Disabled:
            if self.disabled_color is not None:
                return name, resolve_color(self.disabled_color)
            palette = QGuiApplication.palette()
            return name, palette.color(_GROUP.Disabled, _ROLE.Text)
        resolved = resolve_color(color)
        if mode == _MODE.Active:  # hovered
            resolved = resolved.lighter(115) if resolved.lightness() < 128 \
                else resolved.darker(108)
        return name, resolved

    def paint(self, painter, rect, mode, state):
        name, color = self._pick(mode, state)
        rgba = color.name(getattr(QColor, "NameFormat", QColor).HexArgb) \
            if color.alpha() < 255 else color.name()
        renderer = _renderer(name, rgba)
        # Fit the (square) viewBox inside rect, centred.
        side = min(rect.width(), rect.height())
        target = QRectF(rect.x() + (rect.width() - side) / 2.0,
                        rect.y() + (rect.height() - side) / 2.0, side, side)
        renderer.render(painter, target)

    def pixmap(self, size, mode, state):
        pixmap = QPixmap(size)
        pixmap.fill(getattr(Qt, "GlobalColor", Qt).transparent)
        painter = QPainter(pixmap)
        painter.setRenderHint(getattr(QPainter, "RenderHint", QPainter).Antialiasing)
        self.paint(painter, pixmap.rect(), mode, state)
        painter.end()
        return pixmap

    def scaledPixmap(self, size, mode, state, scale):  # Qt 6 HiDPI path
        pixmap = self.pixmap(QSize(int(size.width() * scale),
                                   int(size.height() * scale)), mode, state)
        pixmap.setDevicePixelRatio(scale)
        return pixmap

    def clone(self):
        return TintedSvgIconEngine(self.name, self.color, self.off_name,
                                   self.off_color, self.disabled_color)


def tinted_icon(name, color="Text", *, off_name=None, off_color=None,
                disabled_color=None) -> QIcon:
    """Return a QIcon for tintable SVG *name* (see module docstring)."""
    return QIcon(TintedSvgIconEngine(
        name, color, off_name=off_name, off_color=off_color,
        disabled_color=disabled_color))


def visibility_icon() -> QIcon:
    """Eye in the accent colour when on, muted crossed eye when off."""
    return tinted_icon("visible", "Highlight",
                       off_name="invisible", off_color="PlaceholderText")
