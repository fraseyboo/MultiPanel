"""Generate recolourable (``currentColor``) SVG icons from GUI/icons/svg_icons.

Every single-colour source icon is rewritten into ``GUI/icons/tintable``:

* Inkscape/Sodipodi editor metadata is removed;
* the one colour used is replaced by ``currentColor``, so the UI can draw the
  icon in any colour (see ``GUI/tinted_icons.py``);
* the physical ``width``/``height`` are dropped and the viewBox is padded to a
  centred square, so icons of different aspect ratios sit evenly in square
  buttons.

Multi-colour icons (gradients, embedded images or more than one colour) carry
meaning in their colours and are skipped.

Usage::

    python tools/make_tintable_icons.py            # regenerate the whole set
    python tools/make_tintable_icons.py visible    # only the named icons
"""
from __future__ import annotations

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src" / "multipanel" / "icons" / "svg_icons"
TARGET = ROOT / "src" / "multipanel" / "icons" / "tintable"

SVG_NS = "http://www.w3.org/2000/svg"
EDITOR_NAMESPACES = (
    "http://www.inkscape.org/namespaces/inkscape",
    "http://sodipodi.sourceforge.net/DTD/sodipodi-0.dtd",
)
COLOUR = re.compile(r"#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b")
COLOUR_ATTRS = ("fill", "stroke", "stop-color", "color")
HEADER = (" Generated by tools/make_tintable_icons.py from svg_icons/{name}.svg;"
          " edit the source and regenerate. ")


def _is_editor(tag_or_attr: str) -> bool:
    return any(tag_or_attr.startswith("{" + ns + "}") for ns in EDITOR_NAMESPACES)


def _colours(root) -> set[str]:
    found = set()
    for element in root.iter():
        for attr in COLOUR_ATTRS:
            value = element.get(attr)
            if value and COLOUR.fullmatch(value.strip()):
                found.add(value.strip().lower())
        for match in COLOUR.findall(element.get("style", "")):
            found.add(match.lower())
    return found


def _recolour(root):
    for element in root.iter():
        for attr in COLOUR_ATTRS:
            value = element.get(attr)
            if value and COLOUR.fullmatch(value.strip()):
                element.set(attr, "currentColor")
        style = element.get("style")
        if style:
            element.set("style", COLOUR.sub("currentColor", style))


def _strip_editor_data(root):
    for parent in list(root.iter()):
        for child in list(parent):
            local = child.tag.split("}")[-1]
            if _is_editor(child.tag) or local == "metadata":
                parent.remove(child)
    for element in root.iter():
        for attr in list(element.attrib):
            if _is_editor(attr) or attr in ("{http://www.w3.org/XML/1998/namespace}space",):
                del element.attrib[attr]


def _square_viewbox(root):
    parts = [float(v) for v in root.get("viewBox", "").replace(",", " ").split()]
    if len(parts) != 4:
        raise ValueError("icon has no usable viewBox")
    x, y, w, h = parts
    side = max(w, h)
    root.set("viewBox", " ".join(f"{v:.6g}" for v in (
        x - (side - w) / 2, y - (side - h) / 2, side, side)))
    for attr in ("width", "height", "id", "version"):
        root.attrib.pop(attr, None)


def convert(source: Path) -> Path | None:
    """Write the tintable variant of *source*; return None if skipped."""
    text = source.read_text(encoding="utf-8")
    if "<image" in text or "Gradient" in text:
        return None
    ET.register_namespace("", SVG_NS)
    root = ET.fromstring(text)
    _strip_editor_data(root)
    if len(_colours(root)) > 1:
        return None
    _recolour(root)
    _square_viewbox(root)
    root.insert(0, ET.Comment(HEADER.format(name=source.stem)))
    TARGET.mkdir(parents=True, exist_ok=True)
    target = TARGET / source.name
    ET.ElementTree(root).write(target, encoding="utf-8", xml_declaration=False)
    return target


def main(names: list[str]) -> int:
    sources = ([SOURCE / f"{name}.svg" for name in names] if names
               else sorted(SOURCE.glob("*.svg")))
    written, skipped = [], []
    for source in sources:
        if not source.is_file():
            print(f"missing: {source}", file=sys.stderr)
            return 1
        (written if convert(source) else skipped).append(source.stem)
    print(f"wrote {len(written)} tintable icon(s) to {TARGET.relative_to(ROOT)}")
    if skipped:
        print(f"skipped {len(skipped)} multi-colour icon(s): {', '.join(skipped)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
