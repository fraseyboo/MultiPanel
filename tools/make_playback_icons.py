"""Draw the media-transport icons used by animation playback panels.

Each icon is a set of disjoint filled polygons on a 24 x 24 viewBox (no
holes, so the triangulating icon pipeline handles them directly). Writes,
like ``tools/make_chevrons.py``:

* ``icons/svg_icons/<name>.svg``;
* ``icons/tintable/<name>.svg`` via ``tools/make_tintable_icons.py``;
* ``icons/vtk_icons/<name>.vtk`` via ``multipanel.icon_converter``;
* ``icons/png_icons/<name>.png`` (512 x 512, anti-aliased).

Needs the ``icons`` extra (shapely, svgpathtools, triangle) and Pillow::

    python tools/make_playback_icons.py
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ICONS = ROOT / "src" / "multipanel" / "icons"
sys.path.insert(0, str(ROOT / "src"))

VIEWBOX = 24.0
FILL = "#000000"
PNG_SIZE, PNG_COLOUR, SUPERSAMPLE = 512, (21, 21, 21, 255), 4
ROUNDING = 0.9           # corner radius, in viewBox units


def _rect(x0, y0, x1, y1):
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]


def _play(x0, x1, y0=5.0, y1=19.0):
    return [(x0, y0), (x1, (y0 + y1) / 2), (x0, y1)]


def _reverse(triangle):
    return [(VIEWBOX - x, y) for x, y in triangle]


SHAPES = {
    "play": [_play(7.0, 19.0)],
    "pause": [_rect(6.0, 5.0, 10.0, 19.0), _rect(14.0, 5.0, 18.0, 19.0)],
    "stop": [_rect(6.0, 6.0, 18.0, 18.0)],
    "step_forward": [_play(5.0, 15.0), _rect(16.0, 5.0, 19.5, 19.0)],
    "step_backward": [_reverse(_play(5.0, 15.0)),
                      _rect(4.5, 5.0, 8.0, 19.0)],
    "skip_start": [_rect(4.0, 5.0, 7.0, 19.0),
                   _reverse(_play(4.0, 12.0)), _reverse(_play(11.0, 19.0))],
    # Tab icon: a play triangle with motion streaks.
    "animation": [_play(10.0, 21.0, 4.0, 20.0),
                  _rect(2.5, 6.5, 8.0, 8.5), _rect(1.5, 11.0, 8.0, 13.0),
                  _rect(2.5, 15.5, 8.0, 17.5)],
}


def outline(ring):
    """Round the polygon's corners; return its counter-clockwise exterior."""
    from shapely.geometry import Polygon
    from shapely.geometry.polygon import orient

    shape = (Polygon(ring).buffer(-ROUNDING, join_style="mitre")
             .buffer(ROUNDING, quad_segs=6))
    return list(orient(shape, sign=1.0).exterior.coords)[:-1]


def svg_text(rings):
    path = " ".join(
        "M" + " L".join(f"{x:.3f},{y:.3f}" for x, y in ring) + " Z"
        for ring in rings)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" '
            'viewBox="0 0 24 24">\n'
            '  <!-- MultiPanel playback icon, generated by '
            'tools/make_playback_icons.py -->\n'
            f'  <path fill="{FILL}" d="{path}"/>\n'
            '</svg>\n')


def write_png(rings, path):
    from PIL import Image, ImageDraw

    big = PNG_SIZE * SUPERSAMPLE
    scale = big / VIEWBOX
    image = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    for ring in rings:
        draw.polygon([(x * scale, y * scale) for x, y in ring],
                     fill=PNG_COLOUR)
    image.resize((PNG_SIZE, PNG_SIZE), Image.LANCZOS).save(path)


def write_vtk(svg_path, vtk_path):
    from multipanel.icon_converter import (convert_svg_to_triangles,
                                           save_shapes_as_polydata)

    shapes = convert_svg_to_triangles(str(svg_path), plot=False,
                                      triangulate_opts="pq10")
    save_shapes_as_polydata(shapes, str(vtk_path))


def main(selected=None):
    names = []
    for name, polygons in SHAPES.items():
        if selected and name not in selected:
            continue
        rings = [outline(polygon) for polygon in polygons]
        svg_path = ICONS / "svg_icons" / f"{name}.svg"
        svg_path.write_text(svg_text(rings), encoding="utf-8")
        write_png(rings, ICONS / "png_icons" / f"{name}.png")
        write_vtk(svg_path, ICONS / "vtk_icons" / f"{name}.vtk")
        names.append(name)
        print(f"wrote {name} ({len(rings)} polygons)")
    subprocess.run([sys.executable, str(ROOT / "tools" /
                                        "make_tintable_icons.py"), *names],
                   check=True)


if __name__ == "__main__":
    main(set(sys.argv[1:]) or None)
