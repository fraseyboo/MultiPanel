"""Draw the chevron icons (``chevron_down/up/left/right``) in every format.

The chevron is a two-segment centre line, outlined as a stroke with round
caps and a round join (``shapely``'s buffer), so all four directions are one
shape rotated, and the outline is an exact filled polygon that the icon
pipeline triangulates. Writes, for each direction:

* ``icons/svg_icons/chevron_<d>.svg``: the source (24 x 24 viewBox);
* ``icons/tintable/chevron_<d>.svg``: via ``tools/make_tintable_icons.py``;
* ``icons/vtk_icons/chevron_<d>.vtk``: via ``multipanel.icon_converter``
  (as the library's batch conversion does);
* ``icons/png_icons/chevron_<d>.png``: 512 x 512, anti-aliased.

Needs the ``icons`` extra (shapely, svgpathtools, triangle) and Pillow::

    python tools/make_chevrons.py
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ICONS = ROOT / "src" / "multipanel" / "icons"
sys.path.insert(0, str(ROOT / "src"))

VIEWBOX = 24.0
HALF_SPAN = 5.5          # centre-line half width (a right-angle chevron)
STROKE = 2.4             # stroke width, in viewBox units
FILL = "#000000"
PNG_SIZE, PNG_COLOUR, SUPERSAMPLE = 512, (21, 21, 21, 255), 4

# Centre lines in SVG coordinates (y down), centred on (12, 12).
_C, _H = VIEWBOX / 2, HALF_SPAN
CENTRE_LINES = {
    "down": [(_C - _H, _C - _H / 2), (_C, _C + _H / 2), (_C + _H, _C - _H / 2)],
    "up": [(_C - _H, _C + _H / 2), (_C, _C - _H / 2), (_C + _H, _C + _H / 2)],
    "left": [(_C + _H / 2, _C - _H), (_C - _H / 2, _C), (_C + _H / 2, _C + _H)],
    "right": [(_C - _H / 2, _C - _H), (_C + _H / 2, _C), (_C - _H / 2, _C + _H)],
}


def outline(centre_line):
    """Exterior ring of the stroked centre line (counter-clockwise)."""
    from shapely.geometry import LineString
    from shapely.geometry.polygon import orient

    shape = LineString(centre_line).buffer(
        STROKE / 2, quad_segs=8, cap_style="round", join_style="round")
    return list(orient(shape, sign=1.0).exterior.coords)[:-1]


def svg_text(ring):
    path = "M" + " L".join(f"{x:.3f},{y:.3f}" for x, y in ring) + " Z"
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" '
            'viewBox="0 0 24 24">\n'
            '  <!-- MultiPanel chevron, generated by tools/make_chevrons.py -->\n'
            f'  <path fill="{FILL}" d="{path}"/>\n'
            '</svg>\n')


def write_png(ring, path):
    from PIL import Image, ImageDraw

    big = PNG_SIZE * SUPERSAMPLE
    scale = big / VIEWBOX
    image = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    ImageDraw.Draw(image).polygon([(x * scale, y * scale) for x, y in ring],
                                  fill=PNG_COLOUR)
    image.resize((PNG_SIZE, PNG_SIZE), Image.LANCZOS).save(path)


def write_vtk(svg_path, vtk_path):
    from multipanel.icon_converter import (convert_svg_to_triangles,
                                           save_shapes_as_polydata)

    shapes = convert_svg_to_triangles(str(svg_path), plot=False,
                                      triangulate_opts="pq10")
    save_shapes_as_polydata(shapes, str(vtk_path))


def main():
    names = []
    for direction, centre_line in CENTRE_LINES.items():
        name = f"chevron_{direction}"
        ring = outline(centre_line)
        svg_path = ICONS / "svg_icons" / f"{name}.svg"
        svg_path.write_text(svg_text(ring), encoding="utf-8")
        write_png(ring, ICONS / "png_icons" / f"{name}.png")
        write_vtk(svg_path, ICONS / "vtk_icons" / f"{name}.vtk")
        names.append(name)
        print(f"wrote {name} ({len(ring)} outline points)")
    subprocess.run([sys.executable, str(ROOT / "tools" /
                                        "make_tintable_icons.py"), *names],
                   check=True)


if __name__ == "__main__":
    main()
